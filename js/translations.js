/**
 * Switch active language and update UI strings
 * @param {string} lang - Language code ('en', 'ja', 'ru', 'zh', 'ko', 'ar', 'id')
 */
function setLanguage(lang) {
    const t = window.translations || {};
    if (!t[lang]) lang = 'en';
    // Check Indonesian unlock state
    const isUnlocked = localStorage.getItem('moedev_id_unlocked') === 'true';
    if (lang === 'id' && !isUnlocked) {
        lang = 'en';
    }
    localStorage.setItem('moedev_lang', lang);
    document.documentElement.lang = lang;

    const flagImg = (cc, alt) =>
        `<img src="https://flagcdn.com/20x15/${cc}.png" width="20" height="15" alt="${alt}" style="vertical-align:middle;display:inline-block;">`;

    const langLabels = {
        en: flagImg('us', 'EN'),
        ja: flagImg('jp', 'JA'),
        ru: flagImg('ru', 'RU'),
        zh: flagImg('cn', 'ZH'),
        ko: flagImg('kr', 'KO'),
        ar: flagImg('sa', 'AR'),
        id: flagImg('id', 'ID'),
    };
    const labelHTML = langLabels[lang] || flagImg('us', 'EN');

    const dBtn = document.getElementById('langDropdown');
    if (dBtn) dBtn.innerHTML = labelHTML;

    const mBtn = document.getElementById('langDropdownMobile');
    if (mBtn) mBtn.innerHTML = labelHTML;

    const fBtn = document.getElementById('langDropdownFooter');
    if (fBtn) fBtn.innerHTML = labelHTML;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[lang] && t[lang][key]) {
            el.innerHTML = t[lang][key];
        } else if (t['en'] && t['en'][key]) {
            el.innerHTML = t['en'][key];
        }
    });

    if (typeof renderEditions === 'function') {
        renderEditions();
    }
    if (typeof resetSelection === 'function' && !document.querySelector('.ed-btn.selected')) {
        resetSelection();
    }
}

// Auto-initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    const params = new URLSearchParams(window.location.search);
    const urlLang = params.get('lang');
    const validLangs = ['en', 'ja', 'ru', 'zh', 'ko', 'ar', 'id'];

    if (urlLang && validLangs.includes(urlLang)) {
        if (urlLang === 'id') {
            localStorage.setItem('moedev_id_unlocked', 'true');
        }
        localStorage.setItem('moedev_lang', urlLang);
    }

    const isUnlocked = localStorage.getItem('moedev_id_unlocked') === 'true';
    let savedLang = localStorage.getItem('moedev_lang') || 'en';
    if (savedLang === 'id' && !isUnlocked) savedLang = 'en';
    setLanguage(savedLang);
});


