/**
 * Switch active language and update UI strings
 * @param {string} lang - Language code ('en', 'id', 'ja', 'ru', 'zh', 'ko', 'ar')
 */
function setLanguage(lang) {
    if (!translations[lang]) lang = 'en';
    localStorage.setItem('nookleaf_lang', lang);
    document.documentElement.lang = lang;

    const langLabels = {
        id: '🇮🇩 ID',
        en: '🇺🇸 EN',
        ja: '🇯🇵 JA',
        ko: '🇰🇷 KO',
        ru: '🇷🇺 RU',
        zh: '🇨🇳 ZH',
        ar: '🇸🇦 AR'
    };
    const labelText = '🌐 ' + (langLabels[lang] || '🇺🇸 EN');

    const dBtn = document.getElementById('langDropdown');
    if (dBtn) dBtn.innerText = labelText;

    const mBtn = document.getElementById('langDropdownMobile');
    if (mBtn) mBtn.innerText = labelText;

    const fBtn = document.getElementById('langDropdownFooter');
    if (fBtn) fBtn.innerText = labelText;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        } else if (translations['en'] && translations['en'][key]) {
            el.innerHTML = translations['en'][key];
        } else if (translations['id'] && translations['id'][key]) {
            el.innerHTML = translations['id'][key];
        }
    });

    if (typeof renderEditions === 'function') {
        renderEditions();
    }
    if (typeof resetSelection === 'function' && !document.querySelector('.ed-btn.selected')) {
        resetSelection();
    }
}

// Auto-initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('nookleaf_lang') || 'en';
    setLanguage(savedLang);
});
